"""Generate SnardgeUtils/RecipeData.lua from Wowhead's Forever profession catalogs.

usage: python gen_recipe_data.py <catalog dir> <sell prices json>... <out.lua>

The catalog dir holds catalog_<skillId>.json files fetched from
https://www.wowhead.com/forever/profession-leveling-guides/catalog?skill=<skillId>.
Sell prices map item id to vendor sell price in copper (see the wow-forever knowledge base tools).
"""
import json
import os
import sys

PROFESSIONS = {171: 'Alchemy', 164: 'Blacksmithing', 333: 'Enchanting', 202: 'Engineering',
               165: 'Leatherworking', 197: 'Tailoring', 185: 'Cooking', 129: 'First Aid'}


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    cat_dir, out_path = sys.argv[1], sys.argv[-1]
    sell = {}
    for path in sys.argv[2:-1]:
        sell.update({int(k): v for k, v in json.load(open(path)).items()})

    items, vendors, recipes = {}, {}, {}
    for skill, prof in PROFESSIONS.items():
        path = os.path.join(cat_dir, f'catalog_{skill}.json')
        if not os.path.exists(path):
            continue
        cat = json.load(open(path))['catalog']
        for r in cat['recipes']:
            if not r['creates'] or r['colors'] is None:
                continue
            out, low, high = r['creates']
            entry = {'n': r['name'], 'l': r['learn'], 'c': r['colors'][1:], 'o': out, 'q': (low + high) / 2,
                     'r': [x for pair in r['reagents'] for x in pair]}
            if r['trainer'] or r['starter']:
                entry['src'] = 'trainer' if r['trainer'] else 'known'
                entry['cost'] = r['cost'] or 0
            elif r['vendor']:
                entry['src'] = 'vendor'
                entry['v'] = [[v['npc'], v['price'] or 0, 1 if v['limited'] else 0] for v in r['vendor'] if not v['currency']]
                for v in r['vendor']:
                    vendors[v['npc']] = cat['vendors'].get(str(v['npc']))
            elif r['drop']:
                entry['src'] = 'drop'
            elif r['quest']:
                entry['src'] = 'quest'
            elif r['event']:
                entry['src'] = 'event'
            else:
                entry['src'] = 'other'
            if r['reputation']:
                entry['rep'] = 1
            if r['specialization']:
                entry['spec'] = 1
            recipes.setdefault(prof, {})[r['id']] = entry
            for i in [out] + [x for x, _ in r['reagents']]:
                it = cat['items'].get(str(i))
                if it:
                    items[i] = (it['name'], sell.get(i))

    lines = ['-- Generated by tools/gen_recipe_data.py from Wowhead Forever profession catalogs. Do not edit.',
             'local _, ns = ...', '', 'ns.recipeItems = {']
    for i, (name, price) in sorted(items.items()):
        lines.append(f'\t[{i}] = {{ {lua_str(name)}, {price if price is not None else "nil"} }},')
    lines += ['}', '', 'ns.recipeVendors = {']
    for npc, v in sorted(vendors.items()):
        if v:
            lines.append(f'\t[{npc}] = {{ {lua_str(v["name"])}, {lua_str(v.get("zone") or "")}, {lua_str(v.get("side") or "")} }},')
    lines += ['}', '', 'ns.recipeData = {']
    for prof, rs in sorted(recipes.items()):
        lines.append(f'\t[{lua_str(prof)}] = {{')
        for rid, e in sorted(rs.items()):
            parts = [f'n = {lua_str(e["n"])}', f'l = {e["l"]}', 'c = { %s }' % ', '.join(map(str, e['c'])),
                     f'o = {e["o"]}', f'q = {e["q"]:g}', 'r = { %s }' % ', '.join(map(str, e['r'])), f'src = {lua_str(e["src"])}']
            if 'cost' in e:
                parts.append(f'cost = {e["cost"]}')
            if 'v' in e:
                parts.append('v = { %s }' % ', '.join('{ %d, %d, %d }' % tuple(v) for v in e['v']))
            if e.get('rep'):
                parts.append('rep = true')
            if e.get('spec'):
                parts.append('spec = true')
            lines.append(f'\t\t[{rid}] = {{ {", ".join(parts)} }},')
        lines.append('\t},')
    lines.append('}')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{sum(len(v) for v in recipes.values())} recipes, {len(items)} items, {len(vendors)} vendors -> {out_path}')


if __name__ == '__main__':
    main()
